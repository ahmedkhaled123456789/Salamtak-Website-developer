"""Generate WebP variants of the photos in public/ (run after adding or replacing a photo).

    python scripts/optimize-images.py            # from website/

For every public/<name>.jpg it writes, next to the original:
  public/<name>.webp       same size as the JPEG
  public/<name>-640.webp   640 px wide (cards, phones)
and src/data/imageWidths.ts (original widths, used for accurate `srcset` descriptors).
The JPEGs stay as the fallback for browsers without WebP support. Requires Pillow (pip install Pillow).
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"
MANIFEST = ROOT / "src" / "data" / "imageWidths.ts"
QUALITY = 78
SMALL = 640

widths: dict[str, int] = {}
before = after = 0
for jpg in sorted(PUBLIC.glob("*.jpg")):
    with Image.open(jpg) as im:
        im = im.convert("RGB")
        widths[jpg.stem] = im.width
        full = jpg.with_suffix(".webp")
        im.save(full, "WEBP", quality=QUALITY, method=6)
        small = jpg.with_name(f"{jpg.stem}-{SMALL}.webp")
        if im.width > SMALL:
            im.resize((SMALL, round(im.height * SMALL / im.width)), Image.LANCZOS).save(
                small, "WEBP", quality=QUALITY, method=6
            )
        else:
            im.save(small, "WEBP", quality=QUALITY, method=6)
    before += jpg.stat().st_size
    after += full.stat().st_size

lines = [
    "/** GENERATED by scripts/optimize-images.py — widths of the photos in public/ (px). Do not edit. */",
    "export const imageWidths: Record<string, number> = {",
    *[f"  '{k}': {v}," for k, v in widths.items()],
    "};",
    f"export const SMALL_IMAGE_WIDTH = {SMALL};",
    "",
]
MANIFEST.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(widths)} photos: JPEG {before // 1024} KB -> WebP {after // 1024} KB (+ {SMALL}w variants)")
